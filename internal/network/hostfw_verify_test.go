func TestVerifyDetectsEveryMismatchClass(t *testing.T) {
	spec := testSpec(true)

	t.Run("missing-rule", func(t *testing.T) {
		rules, chains := specKernel(spec, nil)
		rules["filter/FORWARD"] = rules["filter/FORWARD"][1:] // drop the ingress jump
		if ok, class := mustVerify(t, renderDump(rules, chains), spec); ok || class != "missing-rule" {
			t.Fatalf("ok=%v class=%s", ok, class)
		}
	})
	t.Run("duplicate-rule", func(t *testing.T) {
		rules, chains := specKernel(spec, nil)
		fw := rules["filter/FORWARD"]
		rules["filter/FORWARD"] = append(fw, fw[1]) // duplicate the egress jump at the end
		if ok, class := mustVerify(t, renderDump(rules, chains), spec); ok || class != "duplicate-rule" {
			t.Fatalf("ok=%v class=%s", ok, class)
		}
	})
	t.Run("misordered", func(t *testing.T) {
		rules, chains := specKernel(spec, nil)
		fw := rules["filter/FORWARD"]
		// Swap the two entry jumps — relative order among our rules is verified.
		fw[0], fw[1] = fw[1], fw[0]
		if ok, class := mustVerify(t, renderDump(rules, chains), spec); ok || class != "misordered" {
			t.Fatalf("ok=%v class=%s", ok, class)
		}
	})
	t.Run("mutated-rule", func(t *testing.T) {
		rules, chains := specKernel(spec, nil)
		fw := rules["filter/FORWARD"]
		fw[1] = []string{"-i", "veth+", "-p", "udp", "--dport", "444", "-j", "DROP"} // wrong port
		if ok, class := mustVerify(t, renderDump(rules, chains), spec); ok || class != "missing-rule" {
			t.Fatalf("ok=%v class=%s", ok, class)
		}
	})
	t.Run("owned-chain-extra-rule", func(t *testing.T) {
		rules, chains := specKernel(spec, nil)
		key := "filter/" + portDropChain
		rules[key] = append(rules[key], []string{"-p", "tcp", "--dport", "9999", "-j", "DROP"})
		if ok, class := mustVerify(t, renderDump(rules, chains), spec); ok || class != "owned-chain-drift" {
			t.Fatalf("ok=%v class=%s", ok, class)
		}
	})
	t.Run("owned-chain-reordered", func(t *testing.T) {
		rules, chains := specKernel(spec, nil)
		key := "filter/" + portDropChain
		rs := rules[key]
		rs[0], rs[1] = rs[1], rs[0]
		if ok, class := mustVerify(t, renderDump(rules, chains), spec); ok || class != "owned-chain-drift" {
			t.Fatalf("ok=%v class=%s", ok, class)
		}
	})
	t.Run("missing-owned-chain", func(t *testing.T) {
		rules, chains := specKernel(spec, nil)
		if ok, class := mustVerify(t, renderDump(rules, chains[:1]), spec); ok || class != "missing-chain" {
			t.Fatalf("ok=%v class=%s", ok, class)
		}
	})
}

