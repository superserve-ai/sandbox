// dockerKernel overlays the standard Docker chain tree (as dockerd installs
// it, sanitized interface names) onto a spec kernel, with Docker's
// unconstrained jumps ABOVE vmd's — the dockerd-restarted-last ordering.
func dockerKernel(spec hostFWSpec) (map[string][][]string, []string) {
	rules, chains := specKernel(spec, nil)
	fw := rules["filter/FORWARD"]
	rules["filter/FORWARD"] = append([][]string{{"-j", "DOCKER-USER"}, {"-j", "DOCKER-FORWARD"}}, fw...)
	rules["filter/DOCKER-FORWARD"] = [][]string{
		{"-j", "DOCKER-CT"}, {"-j", "DOCKER-INTERNAL"}, {"-j", "DOCKER-BRIDGE"}, {"-i", "docker0", "-j", "ACCEPT"},
	}
	rules["filter/DOCKER-CT"] = [][]string{
		{"-o", "docker0", "-m", "conntrack", "--ctstate", "RELATED,ESTABLISHED", "-j", "ACCEPT"},
	}
	rules["filter/DOCKER-BRIDGE"] = [][]string{{"-o", "docker0", "-j", "DOCKER"}}
	rules["filter/DOCKER"] = [][]string{{"!", "-i", "docker0", "-o", "docker0", "-j", "DROP"}}
	pre := rules["nat/PREROUTING"]
	rules["nat/PREROUTING"] = append([][]string{{"-m", "addrtype", "--dst-type", "LOCAL", "-j", "DOCKER"}}, pre...)
	rules["nat/DOCKER"] = [][]string{{"-i", "docker0", "-j", "RETURN"}}
	post := rules["nat/POSTROUTING"]
	rules["nat/POSTROUTING"] = append([][]string{{"-s", "172.17.0.0/16", "!", "-o", "docker0", "-j", "MASQUERADE"}}, post...)
	chains = append(chains, "filter/DOCKER-USER", "filter/DOCKER-FORWARD", "filter/DOCKER-CT",
		"filter/DOCKER-INTERNAL", "filter/DOCKER-BRIDGE", "filter/DOCKER", "nat/DOCKER")
	return rules, chains
}

// firstRolloutKernel is a host that has never run this vmd: no vmd rules, no
// owned chains — only the built-in chains and whatever foreign content the
