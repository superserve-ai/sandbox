func TestRepairAndStrictForeignRules(t *testing.T) {
	// The entry jumps are TERMINAL for sandbox traffic, so demoting an
	// operator's stricter veth DROP below them would shadow it into a no-op:
	// repair refuses. Below the jumps it is unreachable for sandbox traffic
	// either way — repair proceeds and preserves it.
	spec := testSpec(true)
	strict := []string{"-i", "veth+", "-p", "tcp", "--dport", "22", "-j", "DROP"}

	rules, chains := specKernel(spec, nil)
	fw := rules["filter/FORWARD"]
	fw[0], fw[1] = fw[1], fw[0] // force a repair via misordered jumps
	rules["filter/FORWARD"] = append([][]string{strict}, fw...)
	d, _ := parseIPTablesSave(renderDump(rules, chains))
	if _, err := repairSharedOrdering(context.Background(), d, spec); err == nil {
		t.Fatal("repair demoted a stricter foreign DROP below the terminal jumps")
	}

	rules, chains = specKernel(spec, nil)
	fw = rules["filter/FORWARD"]
	fw[0], fw[1] = fw[1], fw[0]
	rules["filter/FORWARD"] = append(fw, strict)
	k := &fakeKernel{rules: rules, chains: chains}
	defer k.install(t)()
	d, _ = parseIPTablesSave(renderDump(k.rules, k.chains))
	if _, err := repairSharedOrdering(context.Background(), d, spec); err != nil {
		t.Fatalf("repair with strict rule below the jumps: %v", err)
	}
	found := false
	for _, r := range k.rules["filter/FORWARD"] {
		if ruleEqual(r, strict) {
			found = true
		}
	}
	if !found {
		t.Fatal("strict foreign rule below the jumps deleted by repair")
	}
	nd, _ := parseIPTablesSave(renderDump(k.rules, k.chains))
	if ok, class, detail := verifyHostFirewall(nd, spec); !ok {
		t.Fatalf("post-repair verify failed: %s %s", class, detail)
	}
}

